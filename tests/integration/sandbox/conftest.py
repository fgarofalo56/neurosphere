# pyright: reportMissingImports=false
"""Helpers for sandbox CLI tests. Stack-needing tests carry the `integration` marker."""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from collections.abc import Iterator
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
CLI_DIR = REPO_ROOT / "scripts" / "sandbox"
CLI = CLI_DIR / "sbx_cli.py"

if str(CLI_DIR) not in sys.path:
    sys.path.insert(0, str(CLI_DIR))


def compose(*args: str, timeout: int = 600) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["docker", "compose", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


def run_cli(*args: str, timeout: int = 300) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CLI), *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


def cli_json(*args: str) -> dict:
    result = run_cli(*args)
    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
    start = result.stdout.index("{")
    end = result.stdout.rindex("}") + 1
    return json.loads(result.stdout[start:end])


@pytest.fixture(scope="session")
def stack() -> None:
    """Make sure the default emulators are up (idempotent; leaves them running)."""
    if shutil.which("docker") is None:
        pytest.skip("docker is not installed")
    result = compose("up", "-d", "--wait", timeout=900)
    if result.returncode != 0:
        pytest.fail(f"compose up failed:\n{result.stdout}\n{result.stderr}")


@pytest.fixture(scope="session")
def data_dir(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Tiny seeded data set generated by the real generator (item 3)."""
    out = tmp_path_factory.mktemp("sandbox-data")
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "sandbox.generate",
            "--seed",
            "1",
            "--profile",
            "tiny",
            "--cloud",
            "commercial",
            "--out",
            str(out),
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    return out


def fresh_event_hubs() -> None:
    """Restart the Event Hubs emulator (no persistence => empty hub) and wait until it answers."""
    assert compose("restart", "eventhubs").returncode == 0
    assert compose("up", "-d", "--wait", timeout=900).returncode == 0
    from sbx_seam import HubSeam

    deadline = time.monotonic() + 120
    while True:
        try:
            assert HubSeam().event_count() == 0
            return
        except Exception:
            if time.monotonic() > deadline:
                raise
            time.sleep(3)


@pytest.fixture
def empty_hub(stack: None) -> Iterator[None]:
    fresh_event_hubs()
    yield
