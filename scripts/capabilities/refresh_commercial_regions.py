"""Regenerate the Commercial per-region capability rows from the ARM Providers API.

Operator-run, read-only: it needs a logged-in Azure CLI (`az login`) and reads provider
metadata only (`az provider show`); it creates nothing and handles no secrets. It writes
packages/core/neurosphere_core/capabilities/data/commercial_regions.yaml.

What the rows say: the resource type can be created in that region according to the ARM
Providers API. They do not say anything about capacity, SKU, quota, GA status or
authorization, so ga_status is `unverified` and authorization_scope is `none_claimed`.
Foundry models are not covered here (model availability is per model and region).

Usage:
    python scripts/capabilities/refresh_commercial_regions.py [--date YYYY-MM-DD]
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

import yaml

_reconfigure = getattr(sys.stdout, "reconfigure", None)
if _reconfigure is not None:
    _reconfigure(encoding="utf-8")

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "packages/core/neurosphere_core/capabilities/data/commercial_regions.yaml"
SOURCE_URL = "https://learn.microsoft.com/rest/api/resources/providers/get"

# matrix service key -> (ARM provider namespace, resource type)
SERVICES: dict[str, tuple[str, str]] = {
    "aks": ("Microsoft.ContainerService", "managedClusters"),
    "app_service": ("Microsoft.Web", "sites"),
    "cosmos_db": ("Microsoft.DocumentDB", "databaseAccounts"),
    "event_hubs": ("Microsoft.EventHub", "namespaces"),
    "apim": ("Microsoft.ApiManagement", "service"),
    "ai_search": ("Microsoft.Search", "searchServices"),
    "synapse": ("Microsoft.Synapse", "workspaces"),
    "databricks": ("Microsoft.Databricks", "workspaces"),
    "fabric": ("Microsoft.Fabric", "capacities"),
}

_SKIP = re.compile(r"euap|stage|\(|canary|test", re.IGNORECASE)


def normalize(display: str) -> str | None:
    """'East US 2' -> 'eastus2'; None for canary, stage and non-region entries."""
    if _SKIP.search(display):
        return None
    region = re.sub(r"[^a-z0-9]", "", display.lower())
    return region if re.fullmatch(r"[a-z][a-z0-9]{2,39}", region) else None


def provider_locations(az: str, namespace: str, resource_type: str) -> list[str]:
    query = f"resourceTypes[?resourceType=='{resource_type}'].locations[]"
    proc = subprocess.run(
        [az, "provider", "show", "-n", namespace, "--query", query, "-o", "json"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    names = {normalize(loc) for loc in json.loads(proc.stdout)}
    return sorted(n for n in names if n)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--date", default=datetime.now(UTC).date().isoformat())
    args = parser.parse_args(argv)
    az = shutil.which("az")
    if az is None:
        print("az CLI not found; install it and run `az login`.", file=sys.stderr)
        return 2
    rows: list[dict[str, object]] = []
    for service, (namespace, resource_type) in SERVICES.items():
        regions = provider_locations(az, namespace, resource_type)
        print(f"{service}: {len(regions)} regions")
        for region in regions:
            rows.append(
                {
                    "schema_version": "1.1.0",
                    "id": f"{service}.base.commercial.{region}.any",
                    "service": service,
                    "feature": "base",
                    "cloud": "commercial",
                    "region": region,
                    "sku": None,
                    "availability": "available",
                    "ga_status": "unverified",
                    "authorization_scope": "none_claimed",
                    "source_url": SOURCE_URL,
                    "observed_on": args.date,
                    "notes": (
                        f"Region listed for {namespace}/{resource_type} by the ARM Providers "
                        f"API (az provider show) on {args.date}. Means the resource type can be "
                        "created there, not that capacity, a SKU or quota exist; says nothing "
                        "about GA status or authorization."
                    ),
                }
            )
    header = (
        "# Commercial per-region rows generated by "
        "scripts/capabilities/refresh_commercial_regions.py\n"
        "# from the ARM Providers API. Do not hand-edit; re-run the script.\n"
    )
    OUT.write_text(
        header + yaml.safe_dump(rows, sort_keys=False, width=100), encoding="utf-8", newline="\n"
    )
    print(f"wrote {len(rows)} rows to {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
