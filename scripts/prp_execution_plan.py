def frontmatter(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    if not text.startswith("---"):
        return out
    end = text.find("\n---", 3)
    for line in text[3:end].splitlines():
        if ":" in line and not line.startswith(" "):
            key, _, value = line.partition(":")
            out[key.strip()] = value.strip()
    return out


def ownership(text: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {"owns": [], "tier1": [], "tier2_appends": [], "must_not_touch": []}
    block = re.search(r"```ownership\n(.*?)```", text, re.S)
    key = None
    if block:
        for line in block.group(1).splitlines():
            m = re.match(r"^(\w+):", line)
            if m:
                key = m.group(1)
                continue
            m = re.match(r"^\s+-\s+(.+?)\s*$", line)
            if m and key in out:
                out[key].append(m.group(1))
    return out


def load() -> list[dict]:
    prps = []
    for state in ("backlog", "active"):
        for path in sorted((PRPS / state).glob("PRP-*.md")):
            text = path.read_text(encoding="utf-8")
            fm = frontmatter(text)
            title = re.search(r"^# (PRP-\d{2,3}: .+)$", text, re.M)
            stack = bool(re.search(r"holds the compose stack", text, re.I))
            prps.append(
                {
                    "id": re.match(r"PRP-\d+", path.name).group(0),  # type: ignore[union-attr]
                    "stem": path.stem,
                    "rel": f"{state}/{path.name}",
                    "title": title.group(1) if title else path.stem,
                    "wave": fm.get("wave", "?"),
                    "order": int(fm.get("order", "999") or 999),
                    "priority": fm.get("priority", ""),
                    "model": fm.get("model", ""),
                    "review": fm.get("review", ""),
                    "branch": fm.get("branch", ""),
                    "deps": re.findall(r"PRP-\d{2,3}", fm.get("depends_on", "")),
                    "issues": re.findall(r"\d+", fm.get("issues", "")),
                    "serial": sorted(set(re.findall(r"\[serial-after: (PRP-\d{2,3})\]", text))),
                    "stack": stack,
                    "own": ownership(text),
                }
            )
    return prps


def merge_order(members: list[dict]) -> list[dict]:
    """Order a wave by `order`, but after any same-wave PRP it has a serial-after item on."""
    pending = sorted(members, key=lambda p: p["order"])
    in_wave = {p["id"] for p in pending}
    done: list[dict] = []
    while pending:
        merged = {p["id"] for p in done}
        ready = [p for p in pending if all(s in merged for s in p["serial"] if s in in_wave)]
        nxt = ready[0] if ready else pending[0]
        done.append(nxt)
        pending.remove(nxt)
    return done


def wave_key(wave: str) -> int:
    m = re.search(r"\d+", wave)
    return int(m.group()) if m else 999


def render(prps: list[dict]) -> str:
    ids = {p["id"] for p in prps}
    waves: dict[str, list[dict]] = {}
    for p in prps:
        waves.setdefault(p["wave"], []).append(p)
    lines: list[str] = [BEGIN, ""]

    lines += ["## Waves and merge order", ""]
    for wave in sorted(waves, key=wave_key):
        members = merge_order(waves[wave])
        lines += [
            f"### {wave}",
            "",
            "| Merge | PRP | Model | Review | Blocked by | Serial-after items | Holds stack | Branch |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for n, p in enumerate(members, 1):
            deps = ", ".join(d for d in p["deps"] if d in ids) or "none"
            serial = ", ".join(p["serial"]) or "-"
            lines.append(
                f"| {n} | [{p['title']}]({p['rel']}) | {p['model']} | {p['review']} | {deps} | {serial} | {'yes' if p['stack'] else '-'} | `{p['branch']}` |"
            )
        lines += [
            "",
            f"Gate before the next wave: {WAVE_GATES.get(wave, 'integration check passes.')}",
            "",
        ]

    lines += ["## Dependency graph", "", "```mermaid", "flowchart LR"]
    for wave in sorted(waves, key=wave_key):
        lines.append(f"  subgraph {wave}")
        for p in sorted(waves[wave], key=lambda p: p["order"]):
            lines.append(f'    P{p["id"][4:]}["{p["id"]}"]')
        lines.append("  end")
    for p in sorted(prps, key=lambda p: int(p["id"][4:])):
        for d in p["deps"]:
            if d in ids:
                lines.append(f"  P{d[4:]} --> P{p['id'][4:]}")
    lines += [
        "```",
        "",
        "Arrows are logical dependencies (`depends_on`). Waves also order PRPs that only share files; those have no arrow.",
        "",
    ]

    lines += [
        "## Tier-1 file owners per wave",
        "",
        "A Tier-1 file has one owner per wave. Any other PRP touches it only in a `[serial-after]` item.",
        "",
        "| Wave | PRP | Tier-1 files it owns |",
        "|---|---|---|",
    ]
    for wave in sorted(waves, key=wave_key):
        for p in sorted(waves[wave], key=lambda p: p["order"]):
            if p["own"]["tier1"]:
                files = "<br>".join(f"`{f}`" for f in p["own"]["tier1"])
                lines.append(f"| {wave} | {p['id']} | {files} |")
    lines.append("")

    lines += [
        "## Kickoff prompts",
        "",
        "Paste one into a fresh Claude Code session started at the repo root.",
        "",
    ]
    for p in sorted(prps, key=lambda p: (wave_key(p["wave"]), p["order"])):
        deps = [d for d in p["deps"] if d in ids]
        dep_line = (
            f"Before anything else confirm that {', '.join(deps)} are in PRPs/shipped/ on origin/main; if not, stop and say so. "
            if deps
            else ""
        )
        holder = next((q["id"] for q in waves[p["wave"]] if q["stack"]), None)
        if p["stack"] or len(waves[p["wave"]]) == 1:
            stack_line = "You hold the compose stack for this wave. "
        elif holder:
            stack_line = f"{holder} holds the compose stack in this wave: do not run docker compose or make stack-up. "
        else:
            stack_line = (
                "No PRP in this wave is assigned the compose stack: do not run docker compose or make stack-up "
                "unless I confirm no other session is using it. "
            )
        lines += [
            f"### {p['id']} ({p['wave']})",
            "",
            "```text",
            f"/prp:prp-execute PRPs/{p['rel']}",
            "",
            f"Context for this run: wave {p['wave']} of PRPs/EXECUTION-PLAN.md, branch {p['branch']} cut from origin/main, "
            f"implementer model {p['model']}, review {p['review']}. Read PRPs/reference/parallel-build-reference.md first, "
            f"then the PRP. {dep_line}{stack_line}"
            "Edit only the files in the PRP's Ownership block; add lines only to Tier-2 registries; leave Tier-3 generated "
            "files for the final close-out commit after rebasing on main. Do any [serial-after] item only after the named "
            "PRP has merged. No live or paid call without NS_LIVE_APPROVED=1 and my approval in this session; record what "
            "did not run as OPEN. Finish with the PRP's Validation gates, show their output, open the PR and report "
            "what works, what is partial and what is open.",
            "```",
            "",
        ]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    body = HEADER + "\n" + render(load()) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != body:
            print("STALE: PRPs/EXECUTION-PLAN.md; run python scripts/prp_execution_plan.py --write")
            return 1
        print("OK: execution plan current")
        return 0
    if "--write" in sys.argv:
        OUT.write_text(body, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
