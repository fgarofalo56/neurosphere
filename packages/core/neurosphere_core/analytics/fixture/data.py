"""Deterministic synthetic analytics dataset (sandbox only; no real or production data).

One dataset per cloud, never mixed: every record carries the single cloud it was built for.
Two customers, three domains each, a mix of providers/models/outcomes, a few records with an
unattributed (null) domain, and null-bearing metrics (including a model whose duration and
tokens are ALWAYS unknown, so its groups aggregate to unknown). Generated by index arithmetic,
not a random generator, so it is identical on every run and platform.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from decimal import Decimal

from neurosphere_core.analytics.base.models import Cloud
from neurosphere_core.analytics.base.records import AnalyticsRecord

CUSTOMERS = ("contoso", "fabrikam")
DOMAINS = ("retail", "finance", "support")
MODELS = (
    ("azure_openai", "gpt-4o"),
    ("azure_openai", "gpt-4o-mini"),
    ("anthropic", "claude-sonnet"),
    ("azure_openai", "embed-legacy"),  # duration, tokens: always unknown
)
SPAN_KINDS = ("model_call", "tool_call", "retrieval")
OUTCOMES = ("success", "error", "timeout")
START = datetime(2026, 10, 1, 0, 0, tzinfo=UTC)
DEFAULT_SIZE = 720


def domain_id(cloud: Cloud, customer: str, domain: str) -> str:
    return f"{cloud}:{customer}:catalog:domain:{domain}"


def build_dataset(cloud: Cloud, size: int = DEFAULT_SIZE) -> tuple[AnalyticsRecord, ...]:
    records: list[AnalyticsRecord] = []
    for n in range(size):
        customer = CUSTOMERS[n % 2]
        domain = None if n % 23 == 0 else domain_id(cloud, customer, DOMAINS[(n // 2) % 3])
        provider, model = MODELS[(n * 7 + n // 5) % len(MODELS)]
        legacy = model == "embed-legacy"
        currency = "EUR" if n % 13 == 0 else "USD"
        records.append(
            AnalyticsRecord(
                event_id=f"{cloud}-{n:05d}",
                event_time=START + timedelta(minutes=17 * n),
                cloud=cloud,
                customer_id=customer,
                domain_id=domain,
                provider=provider,
                model=model,
                span_kind=None if n % 31 == 0 else SPAN_KINDS[n % 3],
                outcome=OUTCOMES[(n // 3) % 3] if n % 19 else None,
                currency=currency,
                duration_ms=None if legacy or n % 7 == 0 else 40 + (n * 37) % 900,
                input_tokens=None if legacy or n % 5 == 0 else 100 + (n * 53) % 4000,
                output_tokens=None if legacy or n % 11 == 0 else 10 + (n * 29) % 1500,
                cost_amount=None if n % 9 == 0 else Decimal(n % 97 + 1) / Decimal(10_000),
            )
        )
    return tuple(records)
